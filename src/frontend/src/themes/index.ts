export const DEFAULT_THEME_ID = 'mocha';

export function getTheme(id: string): Theme {
  return THEMES.find(t => t.id === id) ?? THEMES[0];
}

function hexToRgb(hex: string): string | null {
  const m = hex.match(/^#([0-9a-f]{6})$/i);
  if (!m) return null;
  const n = parseInt(m[1], 16);
  return `${(n >> 16) & 255},${(n >> 8) & 255},${n & 255}`;
}

export function applyTheme(theme: Theme): void {
  const root = document.documentElement;
  Object.entries(theme.vars).forEach(([k, v]) => {
    root.style.setProperty(k, v);
    // Derive an "-rgb" companion for every hex var so SCSS can do rgba(var(--x-rgb), a)
    // without each theme having to declare the triplets by hand
    if (!k.endsWith('-rgb')) {
      const rgb = hexToRgb(v);
      if (rgb) root.style.setProperty(`${k}-rgb`, rgb);
    }
  });
  root.setAttribute('data-theme', theme.id);
  root.setAttribute('data-dark', theme.dark ? '1' : '0');
  localStorage.setItem('alkopad-theme', theme.id);
}

export function loadSavedTheme(): Theme {
  return getTheme(localStorage.getItem('alkopad-theme') ?? DEFAULT_THEME_ID);
}
